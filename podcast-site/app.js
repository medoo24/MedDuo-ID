// ─── LOCALSTORAGE HELPERS ────────────────────────────────────
function lsKey(epIdx) { return `medduo_ep_${epIdx}`; }
function saveEpisodeData(epIdx, data) {
  localStorage.setItem(lsKey(epIdx), JSON.stringify(data));
}
function loadEpisodeData(epIdx) {
  try {
    const raw = localStorage.getItem(lsKey(epIdx));
    if (raw) return JSON.parse(raw);
  } catch(e) {}
  return null;
}
function deleteEpisodeData(epIdx) {
  localStorage.removeItem(lsKey(epIdx));
}

function getDialogueData(epIdx) {
  return loadEpisodeData(epIdx) || deepClone(EPISODES[epIdx].dialogue);
}

function deepClone(obj) { return JSON.parse(JSON.stringify(obj)); }

// ─── INIT ────────────────────────────────────────────────────
function init() {
  // Load persisted preferences
  const savedDark    = localStorage.getItem('medduo_dark');
  const savedReading = localStorage.getItem('medduo_reading');
  if (savedDark === 'true') setDarkMode(true);
  if (savedReading === 'true') setReadingMode(true);

  renderGrid();
  bindHeaderControls();
  bindToolbar();
}

// ─── GRID ────────────────────────────────────────────────────
function renderGrid() {
  $epGrid.innerHTML = '';
  EPISODES.forEach(ep => {
    const card = document.createElement('div');
    card.className = 'episode-card';
    card.innerHTML = `
      <div class="card-ep-number">الحلقة ${ep.number}</div>
      <div class="card-ep-title">${ep.title}</div>
      <div class="card-ep-desc">${ep.description}</div>
      <div class="card-arrow">←</div>
    `;
    card.addEventListener('click', () => openEpisode(ep.index));
    $epGrid.appendChild(card);
  });
}

// ─── EPISODE VIEW ────────────────────────────────────────────
function openEpisode(idx) {
  state.currentEpisode = idx;
  const ep = EPISODES[idx];
  $epBadge.textContent = `الحلقة ${ep.number}`;
  $epTitle.textContent  = ep.title;
  $epDesc.textContent   = ep.description;

  stopAutoScroll();
  state.filter = 'all';
  $filterBtns.forEach(b => b.classList.remove('active'));
  document.querySelector('.filter-btn[data-filter="all"]').classList.add('active');

  renderDialogue(idx);
  if (state.readingMode) renderReading(idx);

  showView('episode');
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function showView(which) {
  $viewGrid.classList.toggle('active', which === 'grid');
  $viewEpisode.classList.toggle('active', which === 'episode');
}

function renderDialogue(idx) {
  $dialogue.innerHTML = '';
  const data = getDialogueData(idx);

  data.forEach((item, i) => {
    if (item.type === 'section_header') {
      $dialogue.appendChild(makeSectionHeader(item.text, i, idx));
    } else if (item.type === 'sub_header') {
      $dialogue.appendChild(makeSubHeader(item.text, i, idx));
    } else if (item.type === 'speaker') {
      $dialogue.appendChild(makeAddButton(i, idx));
      $dialogue.appendChild(makeBubble(item, i, idx));
    }
  });
  // Final add button
  $dialogue.appendChild(makeAddButton(data.length, idx));

  applyFilter();
}

function renderReading(idx) {
  $reading.innerHTML = '';
  const data = getDialogueData(idx);
  const filter = state.filter; // respect speaker filter in reading mode
  data.forEach(item => {
    if (item.type === 'section_header') {
      const h = document.createElement('div');
      h.className = 'reading-section-header';
      h.textContent = item.text;
      $reading.appendChild(h);
    } else if (item.type === 'sub_header') {
      const h = document.createElement('div');
      h.className = 'reading-sub-header';
      h.textContent = item.text;
      $reading.appendChild(h);
    } else if (item.type === 'speaker') {
      // Apply speaker filter: skip items that don't match
      if (filter !== 'all' && item.speaker !== filter) return;
      const p = document.createElement('p');
      p.className = 'reading-para';
      const speakerSpan = document.createElement('span');
      speakerSpan.className = item.speaker === 'dr_tarek' ? 'reading-speaker-dr' : 'reading-speaker-atef';
      speakerSpan.textContent = (item.speaker === 'dr_tarek' ? 'د. طارق: ' : 'عاطف: ');
      p.appendChild(speakerSpan);
      p.appendChild(document.createTextNode(item.text));
      $reading.appendChild(p);
    }
  });
}

// ─── BUBBLE FACTORY ──────────────────────────────────────────
function makeBubble(item, itemIdx, epIdx) {
  const wrapper = document.createElement('div');
  wrapper.className = `bubble-wrapper ${item.speaker}`;
  wrapper.dataset.itemIndex = itemIdx;
  wrapper.style.animationDelay = `${Math.min(itemIdx * 0.03, 0.5)}s`;

  // Delete button
  const actionsDiv = document.createElement('div');
  actionsDiv.className = 'bubble-actions';
  const delBtn = document.createElement('button');
  delBtn.className = 'bubble-action-btn';
  delBtn.title = 'حذف';
  delBtn.textContent = '🗑️';
  delBtn.addEventListener('click', (e) => {
    e.stopPropagation();
    if (confirm('هل تريد حذف هذه الفقرة؟')) {
      deleteBubble(epIdx, itemIdx);
    }
  });
  actionsDiv.appendChild(delBtn);

  const bubble = document.createElement('div');
  bubble.className = 'bubble';

  // Speaker name
  const speakerEl = document.createElement('div');
  speakerEl.className = 'bubble-speaker';
  speakerEl.textContent = item.speaker === 'dr_tarek' ? 'د. طارق' : 'عاطف';

  // Click speaker name to edit
  speakerEl.addEventListener('click', (e) => {
    e.stopPropagation();
    editSpeakerName(epIdx, itemIdx, speakerEl, item.speaker);
  });

  // Text
  const textEl = document.createElement('div');
  textEl.className = 'bubble-text';
  textEl.textContent = item.text;

  // Double-click to edit text
  textEl.addEventListener('dblclick', (e) => {
    e.stopPropagation();
    editBubbleText(epIdx, itemIdx, textEl, item.text);
  });

  bubble.appendChild(speakerEl);
  bubble.appendChild(textEl);
  wrapper.appendChild(actionsDiv);
  wrapper.appendChild(bubble);
  return wrapper;
}

function makeSectionHeader(text, itemIdx, epIdx) {
  const div = document.createElement('div');
  div.className = 'section-header-block';
  div.dataset.itemIndex = itemIdx;
  div.innerHTML = `
    <div class="sh-line"></div>
    <div class="sh-text">${escHtml(text)}</div>
    <div class="sh-line"></div>
  `;
  return div;
}

function makeSubHeader(text, itemIdx, epIdx) {
  const div = document.createElement('div');
  div.className = 'sub-header-block';
  div.dataset.itemIndex = itemIdx;
  div.textContent = text;
  return div;
}

function makeAddButton(afterIndex, epIdx) {
  const addDiv = document.createElement('div');
  addDiv.className = 'add-between';
  addDiv.dataset.afterIndex = afterIndex;
  const btn = document.createElement('button');
  btn.className = 'add-between-btn';
  btn.title = 'إضافة فقرة';
  btn.textContent = '+';
  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    state.pendingAddIndex = afterIndex;
    showAddPopup(e.clientX, e.clientY);
  });
  addDiv.appendChild(btn);
  return addDiv;
}

// ─── INLINE EDITING ──────────────────────────────────────────
function editBubbleText(epIdx, itemIdx, textEl, originalText) {
  if (textEl.querySelector('textarea')) return;
  const ta = document.createElement('textarea');
  ta.className = 'bubble-textarea';
  ta.value = originalText;
  ta.rows = Math.max(3, Math.ceil(originalText.length / 60));
  textEl.textContent = '';
  textEl.appendChild(ta);
  ta.focus();
  ta.selectionStart = ta.value.length;

  function save() {
    const newText = ta.value.trim();
    updateBubbleField(epIdx, itemIdx, 'text', newText || originalText);
  }

  ta.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      save();
    }
    if (e.key === 'Escape') {
      textEl.textContent = originalText;
    }
  });
  ta.addEventListener('blur', save);
}

function editSpeakerName(epIdx, itemIdx, speakerEl, speakerKey) {
  if (speakerEl.querySelector('input')) return;
  const inp = document.createElement('input');
  inp.className = 'speaker-input';
  inp.value = speakerEl.textContent;
  speakerEl.textContent = '';
  speakerEl.appendChild(inp);
  inp.focus();

  function save() {
    const newName = inp.value.trim();
    if (newName) {
      updateBubbleField(epIdx, itemIdx, 'customName', newName);
    } else {
      speakerEl.textContent = speakerKey === 'dr_tarek' ? 'د. طارق' : 'عاطف';
    }
  }
  inp.addEventListener('blur', save);
  inp.addEventListener('keydown', (e) => {
    if (e.key === 'Enter') save();
    if (e.key === 'Escape') speakerEl.textContent = speakerKey === 'dr_tarek' ? 'د. طارق' : 'عاطف';
  });
}

function updateBubbleField(epIdx, itemIdx, field, value) {
  const data = getDialogueData(epIdx);
  if (data[itemIdx]) {
    data[itemIdx][field] = value;
    saveEpisodeData(epIdx, data);
    renderDialogue(epIdx);
    if (state.readingMode) renderReading(epIdx);
  }
}

function deleteBubble(epIdx, itemIdx) {
  const data = getDialogueData(epIdx);
  data.splice(itemIdx, 1);
  saveEpisodeData(epIdx, data);
  renderDialogue(epIdx);
  if (state.readingMode) renderReading(epIdx);
}

